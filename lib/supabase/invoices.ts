export async function getInvoices(
  companyId: string,
  filters: InvoiceFilters = {},
): Promise<InvoiceListResult> {
  const supabase = await db()
  const { search, status, vendor_id, overdue, page = 1, pageSize = 20 } = filters
  const from = (page - 1) * pageSize
  const to = from + pageSize - 1

  let query = supabase
    .from('invoices')
    .select(INVOICE_SUMMARY_SELECT, { count: 'exact' })
    .eq('company_id', companyId)
    .order('created_at', { ascending: false })
    .range(from, to)

  if (status) query = query.eq('status', status)
  if (vendor_id) query = query.eq('vendor_id', vendor_id)
  if (search) query = query.ilike('invoice_number', `%${search}%`)
  if (overdue) {
    const today = new Date().toISOString().slice(0, 10)
    query = query
      .lt('due_date', today)
      .not('status', 'in', '("paid","cancelled")')
  }

  const { data, error, count } = await query
  if (error) throw error

  return {
    data: (data ?? []) as InvoiceSummary[],
    total: count ?? 0,
    page,
    pageSize,
    hasNextPage: (count ?? 0) > to + 1,
  }
}

export async function getInvoiceById(
  id: string,
  companyId: string,
): Promise<Invoice | null> {
  const supabase = await db()
  const { data, error } = await supabase
    .from('invoices')
    .select(INVOICE_DETAIL_SELECT)
    .eq('id', id)
    .eq('company_id', companyId)
    .single()

  if (error) {
    if (error.code === 'PGRST116') return null
    throw error
  }

  // Sort items and payments by created_at
  if (data?.items) {
    data.items.sort(
      (a: { created_at: string }, b: { created_at: string }) =>
        new Date(a.created_at).getTime() - new Date(b.created_at).getTime(),
    )
  }
  if (data?.payments) {
    data.payments.sort(
      (a: { payment_date: string }, b: { payment_date: string }) =>
        new Date(b.payment_date).getTime() - new Date(a.payment_date).getTime(),
    )
  }

  return data as Invoice
}

export async function createInvoice(
  companyId: string,
  createdBy: string,
  data: InvoiceFormData,
): Promise<Invoice> {
  const supabase = await db()

  const { items, ...fields } = data

  // invoice_number is auto-generated by DB trigger (pass empty string)
  const { data: invoice, error } = await supabase
    .from('invoices')
    .insert({
      company_id: companyId,
      created_by: createdBy,
      invoice_number: '',
      purchase_order_id: fields.purchase_order_id ?? null,
      vendor_id: fields.vendor_id,
      invoice_date: fields.invoice_date,
      due_date: fields.due_date ?? null,
      discount_amount: fields.discount_amount ?? 0,
      currency: fields.currency ?? 'INR',
      notes: fields.notes ?? null,
      status: 'draft',
    })
    .select()
    .single()

  if (error) throw error

  if (items && items.length > 0) {
    const itemRows = items.map((item) => ({
      invoice_id: invoice.id,
      product_id: item.product_id ?? null,
      description: item.description,
      quantity: item.quantity,
      unit_price: item.unit_price,
      tax_percentage: item.tax_percentage ?? 0,
    }))
    const { error: itemsErr } = await supabase.from('invoice_items').insert(itemRows)
    if (itemsErr) throw itemsErr
  }

  const created = await getInvoiceById(invoice.id, companyId)
  return created as Invoice
}

export async function updateInvoice(
  id: string,
  companyId: string,
  data: Partial<InvoiceFormData>,
): Promise<Invoice> {
  const supabase = await db()
  const { items, ...fields } = data

  const nullable = ['purchase_order_id', 'due_date', 'notes'] as const
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const sanitized: Record<string, any> = { ...fields }
  for (const key of nullable) {
    if (key in sanitized && (sanitized[key] === '' || sanitized[key] === undefined)) {
      sanitized[key] = null
    }
  }

  const { error } = await supabase
    .from('invoices')
    .update({ ...sanitized, updated_at: new Date().toISOString() })
    .eq('id', id)
    .eq('company_id', companyId)
  if (error) throw error

  // Replace items if provided
  if (items !== undefined) {
    const { error: delErr } = await supabase
      .from('invoice_items')
      .delete()
      .eq('invoice_id', id)
    if (delErr) throw delErr

    if (items.length > 0) {
      const itemRows = items.map((item) => ({
        invoice_id: id,
        product_id: item.product_id ?? null,
        description: item.description,
        quantity: item.quantity,
        unit_price: item.unit_price,
        tax_percentage: item.tax_percentage ?? 0,
      }))
      const { error: itemsErr } = await supabase.from('invoice_items').insert(itemRows)
      if (itemsErr) throw itemsErr
    }
  }

  const updated = await getInvoiceById(id, companyId)
  return updated as Invoice
}

