export async function getInvoiceStats(companyId: string): Promise<InvoiceStats> {
  const supabase = await db()
  const today = new Date().toISOString().slice(0, 10)
  const monthStart = today.slice(0, 7) + '-01'

  const [totalResult, pendingResult, overdueResult, outstandingResult, paidMonthResult, todayResult] =
    await Promise.all([
      supabase
        .from('invoices')
        .select('id', { count: 'exact', head: true })
        .eq('company_id', companyId),

      supabase
        .from('invoices')
        .select('id', { count: 'exact', head: true })
        .eq('company_id', companyId)
        .eq('status', 'submitted'),

      supabase
        .from('invoices')
        .select('id', { count: 'exact', head: true })
        .eq('company_id', companyId)
        .lt('due_date', today)
        .not('status', 'in', '("paid","cancelled","draft")'),

      supabase
        .from('invoices')
        .select('remaining_amount')
        .eq('company_id', companyId)
        .in('status', ['approved', 'partially_paid']),

      supabase
        .from('payments')
        .select('amount')
        .eq('company_id', companyId)
        .gte('payment_date', monthStart),

      supabase
        .from('payments')
        .select('amount')
        .eq('company_id', companyId)
        .eq('payment_date', today),
    ])

  const outstanding = (outstandingResult.data ?? []).reduce(
    (s: number, r: { remaining_amount: number }) => s + (r.remaining_amount ?? 0),
    0,
  )
  const paidMonth = (paidMonthResult.data ?? []).reduce(
    (s: number, r: { amount: number }) => s + (r.amount ?? 0),
    0,
  )
  const todayPaid = (todayResult.data ?? []).reduce(
    (s: number, r: { amount: number }) => s + (r.amount ?? 0),
    0,
  )

  return {
    total_invoices: totalResult.count ?? 0,
    pending_approval: pendingResult.count ?? 0,
    outstanding_amount: outstanding,
    paid_this_month: paidMonth,
    overdue_count: overdueResult.count ?? 0,
    todays_payments: todayPaid,
  }
}

