export async function getVendorBalances(
  companyId: string,
  page = 1,
  pageSize = 20,
): Promise<{ data: VendorBalance[]; total: number }> {
  const supabase = await db()
  const today = new Date().toISOString().slice(0, 10)

  // Fetch all non-cancelled, non-draft invoices with vendor info
  const { data, error } = await supabase
    .from('invoices')
    .select(
      `vendor_id, total_amount, paid_amount, remaining_amount, due_date,
       vendor:vendors ( id, name )`,
    )
    .eq('company_id', companyId)
    .not('status', 'in', '("cancelled","draft")')

  if (error) throw error

  // Aggregate by vendor
  const map = new Map<
    string,
    {
      vendor_id: string
      vendor_name: string
      total_invoiced: number
      total_paid: number
      outstanding: number
      overdue_amount: number
      invoice_count: number
      oldest_due_date: string | null
    }
  >()

  for (const row of data ?? []) {
    const vid = row.vendor_id
    const existing = map.get(vid) ?? {
      vendor_id: vid,
      vendor_name: (row.vendor as { name: string } | null)?.name ?? '—',
      total_invoiced: 0,
      total_paid: 0,
      outstanding: 0,
      overdue_amount: 0,
      invoice_count: 0,
      oldest_due_date: null,
    }
    existing.total_invoiced += row.total_amount ?? 0
    existing.total_paid += row.paid_amount ?? 0
    existing.outstanding += row.remaining_amount ?? 0
    existing.invoice_count += 1
    if (row.remaining_amount > 0 && row.due_date && row.due_date < today) {
      existing.overdue_amount += row.remaining_amount ?? 0
    }
    if (
      row.due_date &&
      (!existing.oldest_due_date || row.due_date < existing.oldest_due_date)
    ) {
      existing.oldest_due_date = row.due_date
    }
    map.set(vid, existing)
  }

  const all = Array.from(map.values()).sort((a, b) => b.outstanding - a.outstanding)
  const paged = all.slice((page - 1) * pageSize, page * pageSize)

  return { data: paged as VendorBalance[], total: all.length }
}

// ─────────────────────────────────────────────────────────────────────────────
// AGING REPORT
// ─────────────────────────────────────────────────────────────────────────────

export async function getAgingReport(companyId: string): Promise<AgingReport> {
  const supabase = await db()
  const today = new Date()
  const todayStr = today.toISOString().slice(0, 10)

  const { data, error } = await supabase
    .from('invoices')
    .select('remaining_amount, due_date')
    .eq('company_id', companyId)
    .in('status', ['approved', 'partially_paid'])
    .gt('remaining_amount', 0)

  if (error) throw error

  const report: AgingReport = {
    current: { label: 'Current', count: 0, amount: 0 },
    days_1_30: { label: '1–30 days', count: 0, amount: 0 },
    days_31_60: { label: '31–60 days', count: 0, amount: 0 },
    days_61_90: { label: '61–90 days', count: 0, amount: 0 },
    over_90: { label: '90+ days', count: 0, amount: 0 },
  }

  for (const row of data ?? []) {
    const amt = row.remaining_amount ?? 0
    if (!row.due_date || row.due_date >= todayStr) {
      report.current.count++
      report.current.amount += amt
    } else {
      const diffMs = today.getTime() - new Date(row.due_date).getTime()
      const days = Math.floor(diffMs / 86400000)
      if (days <= 30) {
        report.days_1_30.count++
        report.days_1_30.amount += amt
      } else if (days <= 60) {
        report.days_31_60.count++
        report.days_31_60.amount += amt
      } else if (days <= 90) {
        report.days_61_90.count++
        report.days_61_90.amount += amt
      } else {
        report.over_90.count++
        report.over_90.amount += amt
      }
    }
  }

  return report
}

