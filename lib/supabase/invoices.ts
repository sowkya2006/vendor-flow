export async function recordPayment(
  companyId: string,
  createdBy: string,
  data: PaymentFormData,
): Promise<Payment> {
  const supabase = await db()

  // Validate: cannot over-pay
  const { data: inv } = await supabase
    .from('invoices')
    .select('remaining_amount, status, vendor_id')
    .eq('id', data.invoice_id)
    .eq('company_id', companyId)
    .single()

  if (!inv) throw new Error('Invoice not found')
  if (inv.status === 'paid') throw new Error('Invoice is already fully paid')
  if (inv.status === 'cancelled') throw new Error('Cannot pay a cancelled invoice')
  if (inv.status === 'draft') throw new Error('Invoice must be approved before payment')
  if (inv.status === 'submitted') throw new Error('Invoice must be approved before payment')
  if (data.amount > inv.remaining_amount + 0.01) {
    throw new Error(
      `Payment amount (${data.amount}) exceeds remaining balance (${inv.remaining_amount})`,
    )
  }

  // payment_reference auto-generated by DB trigger (pass empty string)
  const { data: payment, error } = await supabase
    .from('payments')
    .insert({
      invoice_id: data.invoice_id,
      company_id: companyId,
      vendor_id: inv.vendor_id,
      payment_reference: '',
      payment_date: data.payment_date,
      payment_method: data.payment_method,
      amount: data.amount,
      notes: data.notes ?? null,
      created_by: createdBy,
    })
    .select()
    .single()

  if (error) throw error
  return payment as Payment
}

export async function getPayments(
  companyId: string,
  filters: PaymentFilters = {},
): Promise<PaymentListResult> {
  const supabase = await db()
  const { vendor_id, invoice_id, payment_method, from_date, to_date, page = 1, pageSize = 30 } = filters
  const from = (page - 1) * pageSize
  const to = from + pageSize - 1

  let query = supabase
    .from('payments')
    .select(
      `*,
       vendor:vendors ( id, name ),
       invoice:invoices ( id, invoice_number, total_amount ),
       created_by_user:users ( id, full_name, email )`,
      { count: 'exact' },
    )
    .eq('company_id', companyId)
    .order('payment_date', { ascending: false })
    .order('created_at', { ascending: false })
    .range(from, to)

  if (vendor_id) query = query.eq('vendor_id', vendor_id)
  if (invoice_id) query = query.eq('invoice_id', invoice_id)
  if (payment_method) query = query.eq('payment_method', payment_method)
  if (from_date) query = query.gte('payment_date', from_date)
  if (to_date) query = query.lte('payment_date', to_date)

  const { data, error, count } = await query
  if (error) throw error

  return {
    data: (data ?? []) as Payment[],
    total: count ?? 0,
    page,
    pageSize,
    hasNextPage: (count ?? 0) > to + 1,
  }
}

