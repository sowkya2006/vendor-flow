const INVOICE_SUMMARY_SELECT = `
  id, invoice_number, invoice_date, due_date, status,
  subtotal, tax_amount, discount_amount, total_amount, paid_amount, remaining_amount,
  currency, created_at, updated_at, vendor_id, purchase_order_id,
  vendor:vendors ( id, name ),
  purchase_order:purchase_orders ( id, po_number )
`

const INVOICE_DETAIL_SELECT = `
  *,
  vendor:vendors ( id, name, email, status ),
  purchase_order:purchase_orders ( id, po_number ),
  items:invoice_items (
    *,
    product:products ( id, name, sku, unit )
  ),
  payments (
    *,
    created_by_user:users ( id, full_name, email )
  )
`

